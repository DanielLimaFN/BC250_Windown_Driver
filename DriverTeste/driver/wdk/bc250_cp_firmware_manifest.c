void Bc250GetCpFirmwareManifestContract(
    BC250_CP_BOOTSTRAP_POLICY *Policy,
    BC250_CP_FIRMWARE_ENTRY *Manifest)
{
    RtlZeroMemory(Policy, sizeof(*Policy));
    RtlZeroMemory(
        Manifest,
        sizeof(*Manifest) * BC250_CP_BOOTSTRAP_FIRMWARE_COUNT);

    Policy->TmrBytes = BC250_CP_CANDIDATE_TMR_BYTES;
    Policy->TmrAlignment = BC250_CP_CANDIDATE_TMR_ALIGNMENT;
    Policy->FirmwareAlignment = BC250_CP_FIRMWARE_ALIGNMENT;

    Manifest[0].FirmwareType = BC250_PSP_FW_CP_PFP;
    Manifest[0].PayloadBytes = BC250_CP_PFP_PAYLOAD_BYTES;
    Manifest[1].FirmwareType = BC250_PSP_FW_CP_ME;
    Manifest[1].PayloadBytes = BC250_CP_ME_PAYLOAD_BYTES;
    Manifest[2].FirmwareType = BC250_PSP_FW_CP_CE;
    Manifest[2].PayloadBytes = BC250_CP_CE_PAYLOAD_BYTES;
    Manifest[3].FirmwareType = BC250_PSP_FW_CP_MEC;
    Manifest[3].PayloadBytes = BC250_CP_MEC_PAYLOAD_BYTES;
    Manifest[4].FirmwareType = BC250_PSP_FW_CP_MEC_JT1;
    Manifest[4].PayloadBytes = BC250_CP_MEC_JT1_PAYLOAD_BYTES;
}

const unsigned char *Bc250GetCpFirmwarePayloadSha256(uint32_t FirmwareType)
{
    switch (FirmwareType) {
    case BC250_PSP_FW_CP_PFP: return g_Bc250PfpSha256;
    case BC250_PSP_FW_CP_ME: return g_Bc250MeSha256;
    case BC250_PSP_FW_CP_CE: return g_Bc250CeSha256;
    case BC250_PSP_FW_CP_MEC: return g_Bc250MecSha256;
    case BC250_PSP_FW_CP_MEC_JT1: return g_Bc250MecJt1Sha256;
    default: return NULL;
    }
}

typedef struct BC250_VRAM_TOPOLOGY_READER_INTERFACE {
    BC250_TOPOLOGY_READ32 Read32;
    void *Context;
    uint32_t IdentityFlags;
    uint32_t Reserved;
} BC250_VRAM_TOPOLOGY_READER_INTERFACE;

typedef struct BC250_VRAM_TOPOLOGY_READER_EVIDENCE {
    BC250_VRAM_TOPOLOGY_SNAPSHOT Snapshot;
    BC250_VRAM_ADDRESS_SPACE AddressSpace;
    BC250_VRAM_TOPOLOGY_STATUS TopologyStatus;
    uint32_t ReadCount;
    uint32_t StablePasses;
} BC250_VRAM_TOPOLOGY_READER_EVIDENCE;

BC250_VRAM_TOPOLOGY_READER_STATUS Bc250CaptureVramTopologyReadonly(
    const BC250_VRAM_TOPOLOGY_READER_INTERFACE *Interface,
    uint64_t CpuVisibleBytes,
    uint32_t SnapshotGeneration,
    BC250_VRAM_TOPOLOGY_READER_EVIDENCE *Evidence);

